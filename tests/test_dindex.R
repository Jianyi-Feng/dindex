# Run: Rscript tests/test_dindex.R  (from the toolkit root)
source("R/dindex.R")
stopifnot(isTRUE(all.equal(d_index(3, 1), 0.5)), d_index(0, 5) == -1, is.na(d_index(0, 0)))
p <- c(0.3, 12, 7e-4); m <- c(0.1, 3, 2e-3)
stopifnot(isTRUE(all.equal(d_index(p, m), d_from_log_ratio(log_ratio(p, m)))))
stopifnot(inherits(try(log_ratio(-1, 2), silent = TRUE), "try-error"))
stopifnot(inherits(try(log_ratio(1, 2, pseudocount = 0), silent = TRUE), "try-error"))
ab <- matrix(c(10, 0, 0, 5, 20, 0, 1, 1, 50, 4, 0, 0), nrow = 3, dimnames = list(c("s1", "s2", "s3"), c("f1", "f2", "f3", "f4")))
tax <- c(f1 = "A", f2 = "B", f3 = "C", f4 = "A")
r <- d_from_table(ab, tax, "A", "B", min_share = 0.5)
stopifnot(isTRUE(all.equal(r["s1", "D"], 9 / 19)), r["s3", "qc"] == "undefined")
ci <- d_ci_counts(c(30, 3000), c(10, 1000))
stopifnot(all(ci$D_lower <= ci$D & ci$D <= ci$D_upper))
stopifnot(inherits(try(d_ci_counts(-1, 2), silent = TRUE), "try-error"))
spot <- read.csv("examples/data/SPOT_sample_Dindex.csv", check.names = FALSE)
stopifnot(max(abs(d_index(spot$Imitervirales_abundance, spot$Algavirales_abundance) - spot$D_index)) < 1e-9)
set.seed(3); tt <- runif(300, 5, 30); df <- data.frame(T = tt, D = pmin(pmax(0.08 * (tt - 17) + rnorm(300, 0, 0.05), -1), 1))
z <- d_zero_point(df, "T", n_boot = 200)
stopifnot(z["ci_low"] < 17, z["ci_high"] > 17)
